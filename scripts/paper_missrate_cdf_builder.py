#!/usr/bin/env python3
"""
paper_missrate_cdf_builder.py

Create paper-ready sample-wise Miss Rate CDF figures for the RME shadow-detection study.

Core idea
---------
For each test sample i, define
    MissRate_i = FN_i / (TP_i + FN_i)
where FN_i is the number of missed shadow pixels and TP_i is the number of correctly
predicted shadow pixels. The empirical CDF is then
    F(x) = P(MissRate <= x)
computed over all test samples for a given model / frequency / threshold.

This script is designed for the use case discussed in the paper draft:
- main figure: 1 x 3 layout for 1750 / 3750 / 5750 MHz
- y-axis normalized to [0, 1] as a true CDF
- optional zoomed figure(s), typically for 1750 MHz when model gaps are subtle
- fixed thresholds such as -70 / -65 / -60 dBm supported
- summary CSV with F(0.05), F(0.10), F(0.20), median, p90

Expected input
--------------
A CSV like per_sample_metrics.csv generated by final_eval_metrics.py or
final_eval_metrics_fixed_threshold.py, with at least the following columns:
    freq_mhz, sample_id, model_tag, threshold_dbm, TP, FP, FN, TN

Example
-------
python paper_missrate_cdf_builder.py \
    --input_csv ./final_results/metrics_fixed_threshold/per_sample_metrics.csv \
    --result_dir ./final_results/paper_cdf \
    --thresholds -70 -65 -60 \
    --main_freqs 1750 3750 5750 \
    --zoom_freqs 1750
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Dict, List, Iterable

import numpy as np
import matplotlib.pyplot as plt

# Default settings aligned with the paper discussion
DEFAULT_FREQS = [1750, 2750, 3750, 4750, 5750]
DEFAULT_MAIN_FREQS = [1750, 3750, 5750]
DEFAULT_ZOOM_FREQS = [1750]

DEFAULT_MODELS = [
    "radiounet-small",
    "radiounet-medium",
    "transpathnet-small",
    "transpathnet-base",
]

MODEL_LABELS = {
    "radiounet-small": "RadioUNet-S (35M)",
    "radiounet-medium": "RadioUNet-M (97M)",
    "transpathnet-small": "TransPathNet-S (38M)",
    "transpathnet-base": "TransPathNet-B (111M)",
}

MODEL_STYLE = {
    "radiounet-small": {"color": "tab:blue", "linestyle": "-", "linewidth": 2.2},
    "radiounet-medium": {"color": "tab:orange", "linestyle": "-", "linewidth": 2.2},
    "transpathnet-small": {"color": "tab:green", "linestyle": "--", "linewidth": 2.2},
    "transpathnet-base": {"color": "tab:red", "linestyle": "--", "linewidth": 2.2},
}


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Build paper-ready Miss Rate CDF figures.")
    p.add_argument("--input_csv", required=True, help="Path to per_sample_metrics.csv")
    p.add_argument("--result_dir", default="./final_results/paper_cdf", help="Output directory")
    p.add_argument("--models", nargs="+", default=DEFAULT_MODELS, choices=DEFAULT_MODELS,
                   help="Model tags to include")
    p.add_argument("--freqs", type=int, nargs="+", default=DEFAULT_FREQS,
                   help="All frequencies to consider")
    p.add_argument("--main_freqs", type=int, nargs="+", default=DEFAULT_MAIN_FREQS,
                   help="Frequencies shown in the main 1xN figure")
    p.add_argument("--zoom_freqs", type=int, nargs="+", default=DEFAULT_ZOOM_FREQS,
                   help="Frequencies for which an additional zoomed figure is generated")
    p.add_argument("--thresholds", type=float, nargs="+", default=[-65.0],
                   help="Fixed shadow threshold(s) in dBm")
    p.add_argument("--threshold_tol", type=float, default=1e-6,
                   help="Tolerance for matching threshold_dbm in CSV")
    p.add_argument("--x_max", type=float, default=1.0, help="Max x-axis value for CDF")
    p.add_argument("--x_step", type=float, default=0.0025, help="Step size of x-grid")
    p.add_argument("--x_tick_step", type=float, default=0.1, help="Tick step for x-axis")
    p.add_argument("--zoom_half_width", type=float, default=0.06,
                   help="Half-width of automatic zoom window around largest model-gap region")
    p.add_argument("--zoom_y_margin", type=float, default=0.05,
                   help="Extra y margin around zoomed CDF range")
    p.add_argument("--summary_x", type=float, nargs="+", default=[0.05, 0.10, 0.20],
                   help="Report F(x) values at these x positions")
    p.add_argument("--dpi", type=int, default=200)
    return p.parse_args()


def read_csv(path: Path) -> List[Dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def save_csv(path: Path, rows: List[Dict[str, object]], fieldnames: List[str]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def match_threshold(a: float, b: float, tol: float) -> bool:
    return abs(float(a) - float(b)) <= tol


def build_sample_rows(records: List[Dict[str, str]]) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for r in records:
        TP = int(float(r["TP"]))
        FP = int(float(r["FP"]))
        FN = int(float(r["FN"]))
        TN = int(float(r["TN"]))
        denom = TP + FN
        miss_rate = np.nan if denom == 0 else FN / denom
        rows.append({
            "freq_mhz": int(float(r["freq_mhz"])),
            "sample_id": int(float(r["sample_id"])),
            "model_tag": r["model_tag"],
            "model_label": MODEL_LABELS.get(r["model_tag"], r["model_tag"]),
            "threshold_dbm": float(r["threshold_dbm"]),
            "TP": TP,
            "FP": FP,
            "FN": FN,
            "TN": TN,
            "miss_rate": float(miss_rate),
        })
    return rows


def get_values(rows: List[Dict[str, object]], freq: int, model_tag: str,
               threshold_dbm: float, tol: float) -> np.ndarray:
    vals = [
        float(r["miss_rate"]) for r in rows
        if int(r["freq_mhz"]) == int(freq)
        and r["model_tag"] == model_tag
        and match_threshold(float(r["threshold_dbm"]), threshold_dbm, tol)
    ]
    arr = np.asarray(vals, dtype=float)
    return arr[np.isfinite(arr)]


def empirical_cdf(values: np.ndarray, x_grid: np.ndarray) -> np.ndarray:
    if len(values) == 0:
        return np.zeros_like(x_grid)
    values = np.sort(values)
    return np.searchsorted(values, x_grid, side="right") / len(values)


def summarize_distribution(values: np.ndarray, xs: Iterable[float]) -> Dict[str, float]:
    out: Dict[str, float] = {}
    if len(values) == 0:
        out["n_samples"] = 0
        out["mean_miss_rate"] = np.nan
        out["median_miss_rate"] = np.nan
        out["p90_miss_rate"] = np.nan
        for x in xs:
            out[f"F({x:.2f})"] = np.nan
        return out

    out["n_samples"] = int(len(values))
    out["mean_miss_rate"] = float(np.mean(values))
    out["median_miss_rate"] = float(np.median(values))
    out["p90_miss_rate"] = float(np.percentile(values, 90))
    for x in xs:
        out[f"F({x:.2f})"] = float(np.mean(values <= x))
    return out


def auto_zoom_window(curves: Dict[str, np.ndarray], x_grid: np.ndarray,
                     half_width: float, y_margin: float) -> Dict[str, float]:
    stacked = np.vstack([v for v in curves.values()])
    gap = stacked.max(axis=0) - stacked.min(axis=0)
    idx = int(np.argmax(gap))
    x_center = float(x_grid[idx])
    x_min = max(0.0, x_center - half_width)
    x_max = min(1.0, x_center + half_width)

    mask = (x_grid >= x_min) & (x_grid <= x_max)
    local_vals = stacked[:, mask]
    y_min = float(max(0.0, np.min(local_vals) - y_margin))
    y_max = float(min(1.0, np.max(local_vals) + y_margin))

    return {
        "x_center": x_center,
        "x_min": x_min,
        "x_max": x_max,
        "y_min": y_min,
        "y_max": y_max,
        "max_gap": float(gap[idx]),
    }


def make_main_figure(rows: List[Dict[str, object]], threshold_dbm: float, freqs: List[int],
                     model_tags: List[str], x_grid: np.ndarray, x_ticks: np.ndarray,
                     tol: float, out_path: Path, dpi: int) -> List[Dict[str, object]]:
    fig, axes = plt.subplots(1, len(freqs), figsize=(4.8 * len(freqs), 4.8), sharex=True, sharey=True)
    if len(freqs) == 1:
        axes = [axes]

    curve_rows: List[Dict[str, object]] = []

    for ax, freq in zip(axes, freqs):
        for tag in model_tags:
            values = get_values(rows, freq, tag, threshold_dbm, tol)
            if len(values) == 0:
                continue
            cdf = empirical_cdf(values, x_grid)
            style = MODEL_STYLE[tag]
            ax.plot(x_grid, cdf, label=MODEL_LABELS[tag], **style)

            for x, y in zip(x_grid, cdf):
                curve_rows.append({
                    "threshold_dbm": threshold_dbm,
                    "freq_mhz": freq,
                    "model_tag": tag,
                    "model_label": MODEL_LABELS[tag],
                    "x": float(x),
                    "cdf": float(y),
                })

        ax.set_title(f"{freq} MHz", fontsize=13, fontweight="bold")
        ax.set_xlabel("Sample-wise Miss Rate", fontsize=11)
        ax.set_xlim(0, 1.0)
        ax.set_ylim(0, 1.0)
        ax.set_xticks(x_ticks)
        ax.set_yticks(np.linspace(0, 1, 6))
        ax.grid(True, alpha=0.3)

    axes[0].set_ylabel("CDF", fontsize=11)
    fig.suptitle(f"Sample-wise Miss Rate CDF (threshold = {threshold_dbm:.1f} dBm)",
                 fontsize=16, fontweight="bold")

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=4, frameon=True, bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=[0, 0.05, 1, 0.93])
    fig.savefig(out_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)

    return curve_rows


def make_zoom_figure(rows: List[Dict[str, object]], threshold_dbm: float, freq: int,
                     model_tags: List[str], x_grid: np.ndarray, tol: float,
                     half_width: float, y_margin: float, out_path: Path,
                     dpi: int) -> Dict[str, object]:
    curves: Dict[str, np.ndarray] = {}
    for tag in model_tags:
        values = get_values(rows, freq, tag, threshold_dbm, tol)
        if len(values) == 0:
            continue
        curves[tag] = empirical_cdf(values, x_grid)

    if len(curves) < 2:
        return {
            "threshold_dbm": threshold_dbm,
            "freq_mhz": freq,
            "x_center": np.nan,
            "x_min": np.nan,
            "x_max": np.nan,
            "y_min": np.nan,
            "y_max": np.nan,
            "max_gap": np.nan,
        }

    zoom = auto_zoom_window(curves, x_grid, half_width, y_margin)

    fig, ax = plt.subplots(figsize=(6.2, 4.8))
    for tag in model_tags:
        if tag not in curves:
            continue
        ax.plot(x_grid, curves[tag], label=MODEL_LABELS[tag], **MODEL_STYLE[tag])

    ax.set_title(f"Zoomed Miss Rate CDF | {freq} MHz | threshold = {threshold_dbm:.1f} dBm",
                 fontsize=14, fontweight="bold")
    ax.set_xlabel("Sample-wise Miss Rate", fontsize=11)
    ax.set_ylabel("CDF", fontsize=11)
    ax.set_xlim(zoom["x_min"], zoom["x_max"])
    ax.set_ylim(zoom["y_min"], zoom["y_max"])
    ax.grid(True, alpha=0.3)
    ax.legend(loc="lower right", fontsize=10)
    fig.tight_layout()
    fig.savefig(out_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)

    return {
        "threshold_dbm": threshold_dbm,
        "freq_mhz": freq,
        **zoom,
    }


def main() -> None:
    args = parse_args()

    input_csv = Path(args.input_csv)
    out_dir = Path(args.result_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    raw_records = read_csv(input_csv)
    sample_rows = build_sample_rows(raw_records)

    # Save normalized sample-wise miss-rate table
    sample_out = out_dir / "samplewise_miss_rate_rows.csv"
    sample_fields = [
        "freq_mhz", "sample_id", "model_tag", "model_label", "threshold_dbm",
        "TP", "FP", "FN", "TN", "miss_rate",
    ]
    save_csv(sample_out, sample_rows, sample_fields)

    x_grid = np.arange(0.0, args.x_max + args.x_step, args.x_step)
    x_ticks = np.arange(0.0, args.x_max + 1e-12, args.x_tick_step)

    summary_rows: List[Dict[str, object]] = []
    curve_rows_all: List[Dict[str, object]] = []
    zoom_rows: List[Dict[str, object]] = []

    # Numeric summary for all requested frequencies and thresholds
    for thr in args.thresholds:
        for freq in args.freqs:
            for tag in args.models:
                values = get_values(sample_rows, freq, tag, thr, args.threshold_tol)
                item = {
                    "threshold_dbm": thr,
                    "freq_mhz": freq,
                    "model_tag": tag,
                    "model_label": MODEL_LABELS[tag],
                }
                item.update(summarize_distribution(values, args.summary_x))
                summary_rows.append(item)

        # Main figure
        main_path = out_dir / f"fig_missrate_cdf_main_th{thr:.1f}.png"
        curve_rows = make_main_figure(
            rows=sample_rows,
            threshold_dbm=thr,
            freqs=args.main_freqs,
            model_tags=args.models,
            x_grid=x_grid,
            x_ticks=x_ticks,
            tol=args.threshold_tol,
            out_path=main_path,
            dpi=args.dpi,
        )
        curve_rows_all.extend(curve_rows)

        # Zoom figures
        for freq in args.zoom_freqs:
            zoom_path = out_dir / f"fig_missrate_cdf_zoom_{freq}MHz_th{thr:.1f}.png"
            zoom_item = make_zoom_figure(
                rows=sample_rows,
                threshold_dbm=thr,
                freq=freq,
                model_tags=args.models,
                x_grid=x_grid,
                tol=args.threshold_tol,
                half_width=args.zoom_half_width,
                y_margin=args.zoom_y_margin,
                out_path=zoom_path,
                dpi=args.dpi,
            )
            zoom_rows.append(zoom_item)

    # Save summary tables
    summary_path = out_dir / "cdf_summary_table.csv"
    summary_fields = [
        "threshold_dbm", "freq_mhz", "model_tag", "model_label",
        "n_samples", "mean_miss_rate", "median_miss_rate", "p90_miss_rate",
    ] + [f"F({x:.2f})" for x in args.summary_x]
    save_csv(summary_path, summary_rows, summary_fields)

    curve_path = out_dir / "cdf_curve_points.csv"
    curve_fields = ["threshold_dbm", "freq_mhz", "model_tag", "model_label", "x", "cdf"]
    save_csv(curve_path, curve_rows_all, curve_fields)

    zoom_path = out_dir / "cdf_zoom_windows.csv"
    zoom_fields = ["threshold_dbm", "freq_mhz", "x_center", "x_min", "x_max", "y_min", "y_max", "max_gap"]
    save_csv(zoom_path, zoom_rows, zoom_fields)

    print("[Done] Paper-ready Miss Rate CDF generation finished.")
    print(f"Input CSV : {input_csv}")
    print(f"Output dir: {out_dir}")
    print(f"Saved     : {sample_out.name}")
    print(f"Saved     : {summary_path.name}")
    print(f"Saved     : {curve_path.name}")
    print(f"Saved     : {zoom_path.name}")
    for thr in args.thresholds:
        print(f"Saved main figure for threshold {thr:.1f} dBm")
        for freq in args.zoom_freqs:
            print(f"Saved zoom figure for {freq} MHz at threshold {thr:.1f} dBm")


if __name__ == "__main__":
    main()
